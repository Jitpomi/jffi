use anyhow::{Context, Result};
use std::{
    collections::HashSet,
    fs,
    path::{Path, PathBuf},
};
use syn::spanned::Spanned;

const MANAGED: &str = "This module is auto-generated by JFFI";

fn enabled(meta: &syn::Meta) -> bool {
    match meta {
        syn::Meta::Path(path) => !path.is_ident("test"),
        syn::Meta::NameValue(value) if value.path.is_ident("target_os") => {
            matches!(&value.value, syn::Expr::Lit(lit) if matches!(&lit.lit, syn::Lit::Str(s) if s.value() == "android"))
        }
        syn::Meta::List(list) => {
            let nested = list.parse_args_with(
                syn::punctuated::Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated,
            );
            let Ok(nested) = nested else { return true };
            if list.path.is_ident("not") {
                !nested.iter().all(enabled)
            } else if list.path.is_ident("any") {
                nested.iter().any(enabled)
            } else {
                nested.iter().all(enabled)
            }
        }
        _ => true,
    }
}
fn active(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().filter(|a| a.path().is_ident("cfg")).all(|a| {
        a.parse_args::<syn::Meta>()
            .map(|m| enabled(&m))
            .unwrap_or(true)
    })
}
fn exported(attr: &syn::Attribute) -> bool {
    attr.path().is_ident("no_mangle")
        || (attr.path().is_ident("unsafe")
            && attr
                .parse_args::<syn::Meta>()
                .is_ok_and(|m| m.path().is_ident("no_mangle")))
}

pub(super) fn existing(core: &Path, package: &str) -> Result<Option<PathBuf>> {
    let symbol = format!(
        "Java_{}_JffiAndroidInit_initNdkContext",
        package.replace('.', "_")
    );
    fn file(
        path: &Path,
        core: &Path,
        symbol: &str,
        seen: &mut HashSet<PathBuf>,
    ) -> Result<Option<PathBuf>> {
        let canonical = path
            .canonicalize()
            .with_context(|| format!("Reading Rust module {}", path.display()))?;
        if !seen.insert(canonical) {
            return Ok(None);
        }
        let source = fs::read_to_string(path)?;
        // Keep updating JFFI's normal generated bridge (including package renames).
        if path == core.join("src/android.rs") && source.contains(MANAGED) {
            return Ok(None);
        }
        let syntax = syn::parse_file(&source)
            .with_context(|| format!("Parsing Rust module {}", path.display()))?;
        let parent = path.parent().unwrap();
        let dir = if matches!(
            path.file_name().and_then(|n| n.to_str()),
            Some("lib.rs" | "mod.rs")
        ) {
            parent.to_path_buf()
        } else {
            parent.join(path.file_stem().unwrap())
        };
        items(&syntax.items, &dir, path, core, symbol, seen)
    }
    fn items(
        nodes: &[syn::Item],
        dir: &Path,
        path: &Path,
        core: &Path,
        symbol: &str,
        seen: &mut HashSet<PathBuf>,
    ) -> Result<Option<PathBuf>> {
        for item in nodes {
            match item {
                syn::Item::Fn(f)
                    if active(&f.attrs)
                        && f.sig.ident == symbol
                        && f.attrs.iter().any(exported)
                        && f.sig.abi.as_ref().is_some_and(|abi| {
                            abi.name
                                .as_ref()
                                .is_none_or(|s| matches!(s.value().as_str(), "C" | "system"))
                        }) =>
                {
                    return Ok(Some(path.to_path_buf()))
                }
                syn::Item::Mod(m) if active(&m.attrs) => {
                    let found = if let Some((_, nested)) = &m.content {
                        items(
                            nested,
                            &dir.join(m.ident.to_string()),
                            path,
                            core,
                            symbol,
                            seen,
                        )?
                    } else {
                        let explicit = m.attrs.iter().find_map(|a| match &a.meta {
                            syn::Meta::NameValue(v) if v.path.is_ident("path") => match &v.value {
                                syn::Expr::Lit(l) => match &l.lit {
                                    syn::Lit::Str(s) => Some(s.value()),
                                    _ => None,
                                },
                                _ => None,
                            },
                            _ => None,
                        });
                        let child = explicit.map(|p| dir.join(p)).unwrap_or_else(|| {
                            let flat = dir.join(format!("{}.rs", m.ident));
                            if flat.exists() {
                                flat
                            } else {
                                dir.join(m.ident.to_string()).join("mod.rs")
                            }
                        });
                        if child.exists() {
                            file(&child, core, symbol, seen)?
                        } else {
                            None
                        }
                    };
                    if found.is_some() {
                        return Ok(found);
                    }
                }
                _ => {}
            }
        }
        Ok(None)
    }
    file(&core.join("src/lib.rs"), core, &symbol, &mut HashSet::new())
}

/// Remove only a duplicate owned by JFFI; preserve all surrounding user source.
pub(super) fn remove_managed_duplicate(core: &Path) -> Result<()> {
    let generated = core.join("src/android.rs");
    if !fs::read_to_string(&generated).is_ok_and(|s| s.contains(MANAGED)) {
        return Ok(());
    }
    let lib = core.join("src/lib.rs");
    let source = fs::read_to_string(&lib)?;
    let syntax = syn::parse_file(&source)?;
    let mut ranges: Vec<_> = syntax
        .items
        .iter()
        .filter_map(|item| match item {
            syn::Item::Mod(m)
                if m.ident == "android"
                    && m.content.is_none()
                    && !m.attrs.iter().any(|a| a.path().is_ident("path")) =>
            {
                let start = m
                    .attrs
                    .first()
                    .map(|a| a.span().byte_range().start)
                    .unwrap_or(m.span().byte_range().start);
                Some(start..m.span().byte_range().end)
            }
            _ => None,
        })
        .collect();
    ranges.sort_by_key(|r| std::cmp::Reverse(r.start));
    let mut repaired = source.clone();
    for range in ranges {
        repaired.replace_range(range, "");
    }
    if repaired != source {
        fs::write(lib, repaired)?;
    }
    fs::remove_file(generated)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    fn fixture() -> PathBuf {
        let p = std::env::temp_dir().join(format!("jffi-existing-bridge-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(p.join("src/platform")).unwrap();
        p
    }
    const SYMBOL: &str = "#[no_mangle] pub unsafe extern \"C\" fn Java_com_example_app_JffiAndroidInit_initNdkContext() {}";
    #[test]
    fn nested_export_prevents_duplicate_and_repairs_only_generated_registration() {
        let p = fixture();
        let lib = "// Keep my comments and formatting.\n#[cfg(target_os = \"android\")]\nmod platform;\n\n#[cfg(target_os = \"android\")]\nmod android;\n";
        fs::write(p.join("src/lib.rs"), lib).unwrap();
        fs::write(p.join("src/platform/mod.rs"), "mod android;").unwrap();
        fs::write(p.join("src/platform/android.rs"), SYMBOL).unwrap();
        fs::write(p.join("src/android.rs"), format!("// {MANAGED}\n{SYMBOL}")).unwrap();
        assert_eq!(
            existing(&p, "com.example.app").unwrap(),
            Some(p.join("src/platform/android.rs"))
        );
        remove_managed_duplicate(&p).unwrap();
        let repaired = fs::read_to_string(p.join("src/lib.rs")).unwrap();
        assert!(repaired.starts_with("// Keep my comments and formatting."));
        assert!(repaired.contains("mod platform;"));
        assert!(!repaired.contains("mod android;"));
        assert_eq!(
            fs::read_to_string(p.join("src/platform/android.rs")).unwrap(),
            SYMBOL
        );
        assert!(!p.join("src/android.rs").exists());
        fs::remove_dir_all(p).unwrap();
    }
    #[test]
    fn ignores_unwired_comments_test_modules_and_other_platforms() {
        let p = fixture();
        fs::write(p.join("src/lib.rs"), format!("// {SYMBOL}\n#[cfg(test)] mod tests {{ {SYMBOL} }}\n#[cfg(target_os = \"windows\")] mod win {{ {SYMBOL} }}")).unwrap();
        fs::write(p.join("src/unused.rs"), SYMBOL).unwrap();
        assert_eq!(existing(&p, "com.example.app").unwrap(), None);
        fs::remove_dir_all(p).unwrap();
    }
    #[test]
    fn respects_path_inline_modules_and_unsafe_export_attributes() {
        let p = fixture();
        fs::write(p.join("src/lib.rs"), "#[path = \"custom.rs\"] mod custom;").unwrap();
        fs::write(
            p.join("src/custom.rs"),
            format!(
                "mod inside {{ {} }}",
                SYMBOL.replace("#[no_mangle]", "#[unsafe(no_mangle)]")
            ),
        )
        .unwrap();
        assert_eq!(
            existing(&p, "com.example.app").unwrap(),
            Some(p.join("src/custom.rs"))
        );
        assert_eq!(existing(&p, "com.different.app").unwrap(), None);
        fs::remove_dir_all(p).unwrap();
    }
    #[test]
    fn managed_root_bridge_remains_updatable_and_custom_root_is_preserved() {
        let p = fixture();
        fs::write(p.join("src/lib.rs"), "mod android;").unwrap();
        fs::write(p.join("src/android.rs"), format!("// {MANAGED}\n{SYMBOL}")).unwrap();
        assert_eq!(existing(&p, "com.example.app").unwrap(), None);
        fs::write(p.join("src/android.rs"), SYMBOL).unwrap();
        assert_eq!(
            existing(&p, "com.example.app").unwrap(),
            Some(p.join("src/android.rs"))
        );
        remove_managed_duplicate(&p).unwrap();
        assert_eq!(
            fs::read_to_string(p.join("src/android.rs")).unwrap(),
            SYMBOL
        );
        fs::remove_dir_all(p).unwrap();
    }
}
